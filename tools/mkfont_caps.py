#!/usr/bin/env python3
"""Generates firmware/fonts_caps.h from firmware/fonts.h: the same fonts without the lowercase letters (a-z), for the
Bluetooth audio image (PX_OWN_FX), whose flash is full: its screen draws a lowercase letter as the capital (ui_text.h
ft_glyph). The glyphs kept are the same bytes; nothing is drawn anew.

   python3 tools/mkfont_caps.py

Run it again after tools/mkfont.py.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "firmware", "fonts.h")
OUT = os.path.join(HERE, "..", "firmware", "fonts_caps.h")


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    text = open(SRC).read()
    names = re.findall(r"static const op_font (FT_[A-Z]+) = ", text)
    out = ["/* GENERATED by tools/mkfont_caps.py from firmware/fonts.h — do not edit. The Bluetooth audio image's fonts (PX_OWN_FX):",
           " * fonts.h's without the lowercase letters, which its screen draws as capitals (ui_text.h ft_glyph). Inter font",
           " * (Rasmus Andersson), SIL Open Font License 1.1, see firmware/fonts/LICENSE-Inter.txt. */",
           "#pragma once",
           "#include <stdint.h>",
           "typedef struct { uint8_t h; const char *chars; uint8_t n; const uint8_t *adv; const uint32_t *off; const uint8_t *bits; } op_font;",
           ""]
    total_in = total_out = 0
    for name in names:
        m = re.search(r'static const op_font %s = \{ (\d+), ("(?:[^"\\]|\\.)*"), (\d+), ' % name, text)
        h, chars_lit, n = int(m.group(1)), m.group(2), int(m.group(3))
        chars = bytes(chars_lit[1:-1], "utf-8").decode("unicode_escape")
        assert len(chars) == n, (name, len(chars), n)
        adv = [int(x, 0) for x in re.search(r"%s_adv\[\d+\] = \{([^}]*)\}" % name, text).group(1).split(",") if x.strip()]
        off = [int(x, 0) for x in re.search(r"%s_off\[\d+\] = \{([^}]*)\}" % name, text).group(1).split(",") if x.strip()]
        bits = [int(x, 0) for x in re.search(r"%s_bits\[\d+\] = \{([^}]*)\}" % name, text).group(1).split(",") if x.strip()]
        keep = [i for i, c in enumerate(chars) if not ("a" <= c <= "z")]
        k_chars, k_adv, k_off, k_bits = "", [], [], []
        for i in keep:
            size = (h * adv[i] + 1) // 2
            k_chars += chars[i]; k_adv.append(adv[i]); k_off.append(len(k_bits))
            k_bits.extend(bits[off[i]:off[i] + size])
        total_in += len(bits); total_out += len(k_bits)
        out.append("/* %s: %d chars of %d (no a-z), %d bytes */" % (name, len(keep), n, len(k_bits)))
        out.append("static const uint8_t %s_adv[%d] = {%s};" % (name, len(k_adv), ", ".join(str(a) for a in k_adv)))
        out.append("static const uint32_t %s_off[%d] = {%s};" % (name, len(k_off), ", ".join(str(o) for o in k_off)))
        out.append("static const uint8_t %s_bits[%d] = {%s};" % (name, len(k_bits), ", ".join("0x%02X" % b for b in k_bits)))
        out.append("static const op_font %s = { %d, %s, %d, %s_adv, %s_off, %s_bits };" % (name, h, c_string(k_chars), len(keep), name, name, name))
        out.append("")
    open(OUT, "w").write("\n".join(out))
    print("fonts_caps.h: %d bytes of glyphs (fonts.h: %d)" % (total_out, total_in))


if __name__ == "__main__":
    main()
